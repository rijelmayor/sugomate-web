-- Enable order INSERT events for authenticated merchant dashboard alerts.
-- Merchant access remains constrained by the existing orders SELECT RLS policies.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'orders'
  ) then
    alter publication supabase_realtime add table public.orders;
  end if;
end
$$;
